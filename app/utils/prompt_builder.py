from typing import List
from langchain.schema import Document


def build_overall_prompt(content: str, context_docs: List[Document], category_codes: List[str]) -> str:
    """
    GPT에게 전달할 프롬프트 생성
    dream_text: 사용자의 꿈 원문
    context_docs: RAG를 통해 검색된 관련 문서 리스트
    category_codes: CSV에서 로드한 꿈 카테고리 코드 리스트
    """
    context = "\n".join([doc.page_content if hasattr(doc, "page_content") else str(doc) for doc in context_docs])

    prompt = f"""
    당신은 전문적인 꿈 해석사이자 정신분석학적 관점을 가진 전문가입니다.
    사용자가 경험한 꿈을 분석하고, 다음 지침을 따라 응답해주세요.

    매우 중요한 지침:
    1. 반드시 JSON 형식으로만 응답합니다.
    2. 모든 필드를 반드시 포함합니다.
    - JSON 구조를 그대로 따르며, 빈 값은 null 또는 ""로 유지합니다.
    - 설명, 코드블록, 따옴표 밖 텍스트는 절대 포함하지 않습니다.
    - 꿈 제목은 부정적 뉘앙스를 피하고 중립/긍정적 표현으로 작성합니다.
    - 꿈 카테고리를 좋지 않은 꿈에 대해 '예언 꿈', '소망 꿈' 등으로 왜곡하지 않습니다.
    - emoji는 반드시 꿈과 연관되게 선택합니다.
    - suggestion은 직관적이고 날카로운 통찰로 사용자가 ‘아, 맞아’ 하고 깨달을 수 있게 만듭니다.

    출력 JSON 구조 예시:
    {{
        "restate": {{
            "emoji": "",
            "title": "",
            "content": "",
            "category": ""
        }},
        "unconscious": {{
            "analysis": ""
        }},
        "suggestion": {{
            "suggestion": ""
        }}
    }}

    지침(형식 엄수):
    - 응답 길이: 충분히 상세하게 (약 800~1000자 가능)
    - 모든 한글 표기
    - 문단 구분을 위해 **섹션 헤더**와 **빈 줄(\\n\\n)** 사용
    - 각 문단은 2~3문장으로 간결하게
    - 섹션 순서와 헤더는 아래를 **정확히** 사용:
      1) unconscious.analysis: "[핵심 요약]" → "[정서·동기]" → "[자유 연상]" → "[현실 연결]"
        - [자유 연상] 작성 규칙:
          - 꿈 텍스트에서 가장 두드러진 상징 1개를 {{"핵심단어"}}로 선정
          - 리스트나 콜론(:) 구분을 사용하지 않고 **상담사가 대화하듯 문단 형식**으로 작성
          - 문단 안에는 자연스럽게 되묻는 질문을 1~2개 포함
          - 예: “{{핵심단어}}는 당신의 삶에서 중요한 의미를 지니는 듯합니다. 이 상징을 떠올리면 특정한 사람이나 장면이 함께 연상되지 않나요? 또한 {{핵심단어}}가 떠오를 때 드는 감정은 어떤 것인지 살펴볼 수 있습니다.”
    - 꿈 제목은 부정적 뉘앙스를 피하고 **중립/긍정적 표현** 사용
    - category는 아래 중 하나의 **영문 코드**로만 작성: {', '.join(category_codes)}
    - 분석 시 무의식적 동기와 감정, 상징 의미를 포함
    - 꿈 재진술 → 무의식 분석 → AI 제안 순서로 구성

    사용자 꿈:
    {content}

    관련 참고 문서:
    {context}

    반드시 JSON 형식으로만 응답하세요. 아래 예시 구조와 섹션/불릿/줄바꿈 형식을 유지하세요:

    {{
      "restate": {{
        "emoji": "🏫",
        "title": "새로운 학교와 도시로 이사하는 꿈",
        "content": "꿈 속에서 나는 새로운 학교와 도시로 이사했습니다. 낯선 건물과 골목을 탐험하며 적응해야 했고, 새로운 친구들을 만나며 긴장과 설렘이 동시에 일었습니다.",
        "category": "DAILY_REFLECTION"
      }},
      "unconscious": {{
        "analysis": "[핵심 요약]\\n새로운 환경으로의 전환에 대한 준비와 적응 의지가 도드라집니다. 설렘과 긴장이 공존하며 변화가 성장의 계기로 인식됩니다.\\n\\n[정서·동기]\\n안전·소속 욕구와 도전·성취 욕구가 교차합니다. 예측가능성을 확보하려는 마음이 새로운 관계와 역할 탐색을 밀어줍니다.\\n\\n[자유 연상]\\n학교라는 상징은 당신의 삶에서 ‘배움과 새로운 시작’을 의미하는 듯합니다. 이 단어를 떠올릴 때 특정한 사람이나 장면이 함께 연상되지 않나요? 아마도 첫 등교일이나 새로운 선생님과의 만남처럼 긴장과 기대가 뒤섞였던 경험이 스쳐갈 수 있습니다. 학교가 주는 분위기 속에서 느껴지는 감정은 무엇이었을까요? 두근거림, 설렘, 혹은 약간의 두려움일 수도 있습니다. 이렇게 떠오르는 기억과 감정을 따라가며 스스로에게 질문을 던져보는 것이 무의식을 이해하는 실마리가 됩니다.\\n\\n[현실 연결]\\n최근 환경 변화(입학·전근·이사·조직 개편 등)에서 초기 혼란을 관리하며 루틴을 재설계하려는 흐름이 보입니다. 작은 실험과 관계 맵핑을 통해 적응 속도가 빨라질 가능성이 큽니다."
      }},
      "suggestion": {{
        "suggestion": "이번 변화 국면을 작게 쪼개어 다루세요. 2주 단위로 목표 1개, 관계 접점 1개, 루틴 1가지를 정하고 매일 10분 검토 루틴을 고정합니다. 불안 신호가 올라올 때는 호흡 4-4-6 카운트를 3회 반복하며 신체 감각을 안정시키고, 그 직후 바로 실행 가능한 다음 행동 1개를 선택합니다."
      }}
    }}
    """

    return prompt


def build_unconscious_prompt(dream_texts: str, context_docs: List[Document]) -> str:
    """
    최근 꿈 7개를 종합해 무의식 분석을 생성하는 프롬프트
    dream_texts: 최근 7개의 텍스트를 \n로 연결한 문자열
    context_docs: RAG로 검색된 관련 문서 리스트
    """
    # 문서 내용 연결
    context = "\n".join([doc.page_content if hasattr(doc, "page_content") else str(doc) for doc in context_docs])

    prompt = f"""
    반드시 **JSON만** 출력하세요. 필수 필드(title, analysis, suggestion)를 모두 포함하고, 코드블록/설명/키 외 텍스트는 금지합니다.

    분석 대상:
    - 최근 7개의 꿈 텍스트를 **개별 사례로 언급하지 말고**, 공통된 패턴·정서·상징만 종합하세요.

    형식 지침(가독성 강화 필수):
    - analysis는 아래 **정확한 섹션 헤더** 3개를 이 순서로 사용하고, 각 문단은 2~3문장, 문단 사이 **빈 줄(\\n\\n)**:
      1) "[정서 패턴]"
      2) "[욕구와 갈등]"
      3) "[에너지/대처 양식]"
    - suggestion은 직관적이고 날카로운 포인트를 잡아 사용자가 ‘아, 맞아!’ 하고 깨닫게 만드는 제안.
    - 전체 길이: analysis 400~600자 내외. 친근하지만 전문적 톤.

    금지 사항:
    - 개별 꿈의 제목/내용/사건, "자주 등장하는 ~~" 같은 표현 언급 금지.
    - 사례 나열 금지, 통합 관점으로만 기술.

    최근 꿈 7개:
    {dream_texts}

    관련 참고 문서:
    {context}

    출력 예시(JSON):
    {{
      "title": "새로운 도전 앞에서 기대와 부담이 교차하는 상태",
      "analysis": "[정서 패턴]\\n설렘과 불안이 공존하며, 결과에 대한 압박이 일시적으로 자의식을 높입니다. 동시에 호기심이 긴장을 완충합니다.\\n\\n[욕구와 갈등]\\n성취·인정 욕구와 안정·회피 욕구가 교차합니다. 통제감 확보와 탐색 욕구 사이에서 균형을 찾으려는 흔적이 보입니다.\\n\\n[에너지/대처 양식]\\n작게 쪼개 실행하는 미시적 대처가 유효했으며, 반추보다 행동이 정서를 완화하는 경향이 관찰됩니다.",
      "suggestion": "새로운 환경에 적응하며 자신감을 키워보세요. 작은 목표부터 차근차근 시작하고, 새로운 사람들과 경험을 통해 배우는 기회를 적극적으로 찾아보세요. 긴장과 불안은 자연스러운 감정이니, 이를 받아들이고 자신만의 방식으로 환경에 적응하는 연습을 해보는 것이 좋습니다."
    }}
    """

    return prompt
